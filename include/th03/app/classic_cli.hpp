#ifndef TH03_APP_CLASSIC_CLI_HPP
#define TH03_APP_CLASSIC_CLI_HPP

#include <cstddef>
#include <cstdint>
#include <expected>
#include <filesystem>
#include <optional>
#include <span>
#include <string_view>

#include "th03/app/classic_runner.hpp"

namespace th03::app {

enum class ClassicCliOption : std::uint8_t {
	none,
	help,
	classic,
	data,
	main_executable,
	mainl_executable,
	op_executable,
	font_rom,
	rhythm_rom,
	rhythm_pcm,
	config,
	score,
	tick_rate,
	seed,
	smoke_ticks,
};

enum class ClassicCliErrorCode : std::uint8_t {
	unknown_option,
	missing_value,
	duplicate_option,
	missing_required_option,
	invalid_tick_rate,
	invalid_seed,
	invalid_smoke_ticks,
};

struct ClassicCliError final {
	ClassicCliErrorCode code = ClassicCliErrorCode::unknown_option;
	ClassicCliOption option = ClassicCliOption::none;
	std::size_t argument_index = 0U;
};

struct ClassicCliRequest final {
	bool show_help = false;
	ClassicRunnerRequest launch{};
	RationalTickRate tick_rate = pc98_24khz_nominal_tick_rate;
	// Optional caller-supplied YM2608 ADPCM-A image. The launcher validates the
	// exact 8 KiB size and the audio engine takes its own copy.
	std::optional<std::filesystem::path> rhythm_rom{};
	// Optional decoded six-voice reference package generated by the standalone
	// builder from an authenticated T98-Next Sound86 device module.
	std::optional<std::filesystem::path> rhythm_pcm{};
	std::optional<std::uint64_t> smoke_ticks{};
};

// Parses arguments after argv[0]. The nominal PC-9801 24 kHz cadence is the
// default; --tick-rate remains an explicit developer/host override.
[[nodiscard]] std::expected<ClassicCliRequest, ClassicCliError>
parse_classic_cli(std::span<const std::string_view> arguments);

} // namespace th03::app

#endif
