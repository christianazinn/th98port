#ifndef TH03_PRESENT_SPRITE_STAGING_HPP
#define TH03_PRESENT_SPRITE_STAGING_HPP

#include <array>
#include <cstddef>
#include <cstdint>
#include <optional>

#include "th03/assets/types.hpp"
#include "th03/present/raster.hpp"

namespace th03::present {

// The two decoded character BF2 sheets are injected in the same P1-then-P2
// order as set_callbacks_*() / sub_A4C3(). No filename or filesystem policy
// crosses this boundary.
struct MainPlayerShotSheets {
	const assets::BfntSheet *player_one = nullptr;
	const assets::BfntSheet *player_two = nullptr;
};

// SPRITE16 treats the lower 200 rows of each 640x400 graphics page as one
// packed source plane. Offsets used by MAIN are relative to this rectangle.
inline constexpr std::uint16_t sprite16_source_top = 200U;
inline constexpr std::uint16_t sprite16_source_width = graphics_width;
inline constexpr std::uint16_t sprite16_source_height = 200U;
inline constexpr std::size_t sprite16_source_stride =
	static_cast<std::size_t>(sprite16_source_width) / 8U;
inline constexpr std::size_t sprite16_source_plane_size =
	sprite16_source_stride * sprite16_source_height;

// Owns the two masks generated by SPRITE16_GENERATE_ALPHA. Color pixels stay
// in Raster's source rows, just as the original keeps them in VRAM rather than
// duplicating them into conventional memory.
class Sprite16Staging {
public:
	// Exact sub_E266() placement for the two decoded character BF2 sheets.
	// This is intentionally separate from commit(): MAIN restores its palette
	// and changes raster mode between these source operations.
	[[nodiscard]] bool stage_main_shots(
		Raster &raster,
		MainPlayerShotSheets sheets
	);

	// Mirrors sprite16_sprites_commit(): copy page 0's complete lower-half
	// source area to page 1, leave page 0 accessed, and derive both the positive
	// (opaque) and complemented negative (transparent) masks from page 0.
	[[nodiscard]] bool commit(Raster &raster);

	[[nodiscard]] bool committed() const noexcept;
	[[nodiscard]] std::optional<BitSource> positive_alpha() const noexcept;
	[[nodiscard]] std::optional<BitSource> negative_alpha() const noexcept;

private:
	std::array<std::uint8_t, sprite16_source_plane_size> positive_alpha_{};
	std::array<std::uint8_t, sprite16_source_plane_size> negative_alpha_{};
	bool committed_ = false;
};

} // namespace th03::present

#endif
