#!/usr/bin/env python3
"""Generate the fixed TH03 PMD 166400 -> 48000 Hz FIR table."""

from __future__ import annotations

import argparse
import math
from pathlib import Path


TAPS = 128
PHASES = 15
LEFT_SPAN = 63
HALF_WIDTH = 64.0
Q_SCALE = 1 << 30
# 20,000 / 166,400 cycles per input sample, reduced exactly.
CUTOFF = 25.0 / 208.0


def round_away(value: float) -> int:
    scaled = value * Q_SCALE
    if scaled >= 0.0:
        return int(math.floor(scaled + 0.5))
    return int(math.ceil(scaled - 0.5))


def generate() -> list[list[int]]:
    result: list[list[int]] = []
    for phase in range(PHASES):
        fraction = phase / PHASES
        floating: list[float] = []
        for tap in range(TAPS):
            offset = tap - LEFT_SPAN
            delta = fraction - offset
            argument = 2.0 * CUTOFF * delta
            sinc = 1.0
            if argument != 0.0:
                sinc = math.sin(math.pi * argument) / (math.pi * argument)
            window = (
                0.42
                + 0.5 * math.cos(math.pi * delta / HALF_WIDTH)
                + 0.08 * math.cos(2.0 * math.pi * delta / HALF_WIDTH)
            )
            floating.append(2.0 * CUTOFF * sinc * window)

        total = sum(floating)
        normalized = [coefficient / total for coefficient in floating]
        fixed = [round_away(coefficient) for coefficient in normalized]
        correction_index = max(
            range(TAPS), key=lambda index: abs(normalized[index])
        )
        fixed[correction_index] += Q_SCALE - sum(fixed)
        if sum(fixed) != Q_SCALE:
            raise RuntimeError("phase normalization failed")
        result.append(fixed)
    return result


def magnitude(phase: list[int], frequency_hz: int) -> float:
    real = 0.0
    imaginary = 0.0
    for tap, coefficient in enumerate(phase):
        angle = 2.0 * math.pi * frequency_hz * (tap - LEFT_SPAN) / 166_400.0
        normalized = coefficient / Q_SCALE
        real += normalized * math.cos(angle)
        imaginary -= normalized * math.sin(angle)
    return math.hypot(real, imaginary)


def validate_response(coefficients: list[list[int]]) -> None:
    passband = [
        magnitude(phase, frequency)
        for frequency in range(0, 17_001, 100)
        for phase in coefficients
    ]
    stopband = [
        magnitude(phase, frequency)
        for frequency in range(24_000, 83_201, 100)
        for phase in coefficients
    ]
    # These bounds include the quantized table, not the floating design. They
    # lock <=0.025 dB passband droop through 17 kHz and >=75 dB rejection from
    # the 24 kHz output Nyquist through the input Nyquist.
    if min(passband) < 0.99712 or max(passband) > 1.0002:
        raise RuntimeError("generated passband is outside the locked response")
    if max(stopband) > 0.000177:
        raise RuntimeError("generated stopband is outside the locked response")


def render(coefficients: list[list[int]]) -> str:
    maximum_l1 = max(sum(abs(value) for value in phase) for phase in coefficients)
    lines = [
        "// Generated by tools/generate_audio_resampler_coefficients.py.",
        "// 128-tap Blackman-windowed sinc, cutoff 20 kHz, signed Q30.",
        "inline constexpr std::array<",
        "\tstd::array<std::int32_t, pmd_resampler_tap_count>,",
        "\tpmd_resampler_phase_count",
        "> pmd_resampler_coefficients{{",
    ]
    for phase in coefficients:
        lines.append("\t{{")
        for start in range(0, TAPS, 8):
            values = ", ".join(str(value) for value in phase[start : start + 8])
            lines.append(f"\t\t{values},")
        lines.append("\t}},")
    lines.extend(
        [
            "}};",
            "inline constexpr std::int64_t pmd_resampler_maximum_l1 =",
            f"\t{maximum_l1}LL;",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path)
    parser.add_argument("--check", type=Path)
    arguments = parser.parse_args()
    if (arguments.output is None) == (arguments.check is None):
        parser.error("specify exactly one of --output or --check")

    coefficients = generate()
    validate_response(coefficients)
    generated = render(coefficients)
    if arguments.check is not None:
        if arguments.check.read_text(encoding="utf-8") != generated:
            raise SystemExit("generated coefficient table differs")
        return 0

    arguments.output.write_text(generated, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
